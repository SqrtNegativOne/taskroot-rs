/// The settings screen's tab/section/setting metadata, derived from the
/// `#[setting(..)]` attributes on [`AppSettings`].
#[tauri::command]
#[must_use]
pub fn get_settings_schema() -> Value {
    metadata::settings_schema_value()
}

#[tauri::command]
pub async fn get_settings(app: tauri::AppHandle) -> Result<AppSettings, AppError> {
    let pool = crate::db_pool(&app)?;
    storage::read_settings(&pool).await
}

#[tauri::command]
pub async fn update_setting(
    app: tauri::AppHandle,
    key: String,
    value: Value,
) -> Result<(), AppError> {
    let pool = crate::db_pool(&app)?;
    storage::write_setting(&pool, &key, &value).await
}

/// Read per-component UI state (filters, sorts, view modes, pane sizes) from the
/// dedicated `ui_state` table. Returns `null` for an unknown key.
#[tauri::command]
pub async fn get_ui_state(app: tauri::AppHandle, key: String) -> Result<Value, AppError> {
    let pool = crate::db_pool(&app)?;
    storage::read_ui_state(&pool, &key).await
}

/// Persist per-component UI state. See [`get_ui_state`].
#[tauri::command]
pub async fn set_ui_state(
    app: tauri::AppHandle,
    key: String,
    value: Value,
) -> Result<(), AppError> {
    let pool = crate::db_pool(&app)?;
    storage::write_ui_state(&pool, &key, &value).await
}
