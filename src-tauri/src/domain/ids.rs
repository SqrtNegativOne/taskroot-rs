#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq, std::hash::Hash)]
#[serde(try_from = "String", into = "String")]
pub struct Color(pub String);
impl TryFrom<String> for Color {
    type Error = String;
    fn try_from(s: String) -> Result<Self, Self::Error> {
        if s.starts_with('#') && (s.len() == 7 || s.len() == 9) {
            Ok(Self(s))
        } else {
            Err(format!("Invalid color format: '{s}'"))
        }
    }
}
impl From<Color> for String {
    fn from(c: Color) -> Self {
        c.0
    }
}
impl std::fmt::Display for Color {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.0)
    }
}

impl_ts_string_newtype!(TaskId, EventId, RemoteId, CollectionId, Color);

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq, TS)]
#[ts(export, export_to = "../../src/lib/bindings/WindowLabel.generated.ts")]
#[serde(rename_all = "kebab-case")]
pub enum WindowLabel {
    Main,
    Launcher,
    Minitracker,
    Effect,
}

impl WindowLabel {
    #[must_use]
    pub const fn as_str(&self) -> &'static str {
        match self {
            Self::Main => "main",
            Self::Launcher => "launcher",
            Self::Minitracker => "minitracker",
            Self::Effect => "effect",
        }
    }
}
