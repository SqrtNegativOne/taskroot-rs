//! App settings and per-component UI state storage.
//!
//! Both live in JSON files in the app data directory:
//! - `settings.json` holds one [`AppSettings`] object, read/written by
//!   [`get_settings`] / [`update_setting`].
//! - `ui-state.json` is a flat `{ key: value }` map for arbitrary per-component
//!   UI state (filters, sorts, view modes, pane sizes) via [`get_ui_state`] /
//!   [`set_ui_state`].
//!
//! The rule: if it is a typed app setting, it belongs in `AppSettings`; anything
//! else the frontend wants to remember goes to `ui-state.json`. Never smuggle UI
//! state into `settings.json` as ad-hoc `ui.*` keys.
//!
//! Settings presentation metadata lives in `#[setting(..)]` attributes next to the
//! field it describes; `commands::settings::get_settings_schema` assembles the UI
//! schema from them and [`AppSettings::setting_metadata`] is generated by
//! `#[derive(SettingsMeta)]`.
//!
//! This module is split into [`storage`] (the store-level command bodies) and
//! [`metadata`] (schema assembly); the IPC commands live in `commands::settings`.

