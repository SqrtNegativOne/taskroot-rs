/// One setting's presentation metadata, generated by `#[derive(SettingsMeta)]`.
///
/// Serialized into the `get_settings_schema` payload. `section` is not serialized:
/// it only routes the setting into the right tab/section during assembly.
#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SettingMeta {
    pub id: String,
    pub label: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,
    pub keywords: Vec<String>,
    #[serde(rename = "type")]
    pub kind: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub options: Option<Vec<SettingOption>>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub min: Option<i64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub max: Option<i64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub default_value: Option<Value>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub danger: Option<bool>,
    #[serde(skip)]
    pub section: &'static str,
}

/// A select option; `value` is JSON so it can be a string or a number.
#[derive(Debug, Clone, Serialize)]
pub struct SettingOption {
    pub value: Value,
    pub label: String,
}

