//! Setting presentation metadata and the settings-screen schema.
//!
//! [`SettingMeta`] is generated from the `#[setting(..)]` attributes on
//! `AppSettings` by `#[derive(SettingsMeta)]`; this module only assembles the
//! generated metadata into tabs/sections for `get_settings_schema`.

use serde::{Deserialize, Serialize};
use serde_json::Value;
use specta::Type;

use super::AppSettings;

/// Control kind rendered by the Settings screen for a [`SettingMeta`] row.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Type)]
#[serde(rename_all = "lowercase")]
pub enum SettingKind {
    Select,
    Checkbox,
    Number,
    Time,
    Calendar,
}

/// One setting's presentation metadata, generated by `#[derive(SettingsMeta)]`.
///
/// Serialized into the `get_settings_schema` payload. `section` is not serialized:
/// it only routes the setting into the right tab/section during assembly.
#[derive(Debug, Clone, Serialize, Type)]
#[serde(rename_all = "camelCase")]
pub struct SettingMeta {
    pub id: String,
    pub label: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,
    pub keywords: Vec<String>,
    #[serde(rename = "type")]
    pub kind: SettingKind,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub options: Option<Vec<SettingOption>>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub min: Option<i64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub max: Option<i64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub default_value: Option<Value>,
    #[serde(skip)]
    pub section: &'static str,
}

/// A select option; `value` is JSON so it can be a string or a number.
#[derive(Debug, Clone, Serialize, Type)]
pub struct SettingOption {
    pub value: Value,
    pub label: String,
}

/// A tab/section in the settings screen. `key` is what `#[setting(section = ..)]`
/// references; tabs are grouped in first-appearance order.
struct SectionDef {
    key: &'static str,
    tab: &'static str,
    tab_label: &'static str,
    name: &'static str,
}

const SETTING_SECTIONS: &[SectionDef] = &[
    SectionDef {
        key: "app_appearance",
        tab: "appearance",
        tab_label: "Appearance",
        name: "Theme",
    },
    SectionDef {
        key: "plan_calendar",
        tab: "plan_screen",
        tab_label: "Plan screen",
        name: "Calendar",
    },
    SectionDef {
        key: "do_stopwatch",
        tab: "do_screen",
        tab_label: "Do screen",
        name: "Stopwatch",
    },
    SectionDef {
        key: "tracker_appearance",
        tab: "tracker_window",
        tab_label: "Tracker window",
        name: "Appearance",
    },
    SectionDef {
        key: "focus_feed",
        tab: "integrations",
        tab_label: "Integrations",
        name: "Focus feed",
    },
];

#[derive(Debug, Clone, Serialize, Type)]
pub struct SettingSection {
    pub name: String,
    pub settings: Vec<SettingMeta>,
}

#[derive(Debug, Clone, Serialize, Type)]
pub struct SettingTab {
    pub id: String,
    pub label: String,
    pub sections: Vec<SettingSection>,
}

#[derive(Debug, Clone, Serialize, Type)]
pub struct SettingsSchema {
    pub tabs: Vec<SettingTab>,
}

/// Assemble the settings screen's tab/section/setting schema.
///
/// Tests assert the wire contract structurally rather than pinning a full golden
/// blob, which would be a change-detector.
#[must_use]
pub fn settings_schema() -> SettingsSchema {
    let mut tabs: Vec<SettingTab> = Vec::new();
    let metadata = AppSettings::setting_metadata();

    for def in SETTING_SECTIONS {
        let settings: Vec<SettingMeta> = metadata
            .iter()
            .filter(|meta| meta.section == def.key)
            .cloned()
            .collect();

        let section = SettingSection {
            name: def.name.to_string(),
            settings,
        };

        if let Some(tab) = tabs.iter_mut().find(|tab| tab.id == def.tab) {
            tab.sections.push(section);
        } else {
            tabs.push(SettingTab {
                id: def.tab.to_string(),
                label: def.tab_label.to_string(),
                sections: vec![section],
            });
        }
    }

    SettingsSchema { tabs }
}

