//! App settings and per-component UI state storage.
//!
//! Two channels back persisted state:
//! - Typed, user-facing app settings are `AppSettings` fields stored as JSON rows
//!   in the `settings` table and read/written with [`get_settings`] / [`update_setting`].
//! - Arbitrary per-component UI state (filters, sorts, view modes, pane sizes)
//!   lives in the dedicated `ui_state` table via [`get_ui_state`] / [`set_ui_state`].
//!
//! The rule: if it is a typed app setting, it belongs in `AppSettings`; anything
//! else the frontend wants to remember goes to `ui_state`. Never smuggle UI state
//! into `settings` as ad-hoc `ui.*` keys. (The `settings` table also carries the
//! `google_*` OAuth rows written by `auth.rs`; those are not settings and are not
//! part of `AppSettings`.)
//!
//! Settings presentation metadata lives in `#[setting(..)]` attributes next to the
//! field it describes; [`get_settings_schema`] assembles the UI schema from them
//! and [`AppSettings::setting_metadata`] is generated by `#[derive(SettingsMeta)]`.
//!
//! This module is split into [`storage`] (the pool-level command bodies, value
//! decode/encode and the merge rule) and [`metadata`] (schema assembly); the
//! command functions stay here and only resolve the pool.
